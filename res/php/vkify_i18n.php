if (!function_exists('vkifyTr')) {
    function vkifyTr(string $name, ...$args): string
    {
        $strings = vkifyGetStrings();
        $lang = getLanguage();
        $text = $strings[$lang][$name] ?? $strings['en'][$name] ?? '@' . $name;

        foreach ($args as $i => $arg) {
            $text = str_replace('$' . ($i + 1), htmlspecialchars((string) $arg, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'), $text);
        }

        return $text;
    }
}

if (!function_exists('vkifyGetLang')) {
    function vkifyGetLang(?string $lang = null): array
    {
        $strings = vkifyGetStrings();
        $lang ??= getLanguage();
        return $strings[$lang] ?? $strings['en'];
    }
